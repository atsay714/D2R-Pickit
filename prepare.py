"""Generate the limited gems/runes/keys/potions pickup catalog."""
from pathlib import Path
import argparse
import csv
import json

ROOT = Path(__file__).resolve().parent
VANILLA = {
    "gems": "gcv gfv gsv gzv gpv gcy gfy gsy gly gpy gcb gfb gsb glb gpb gcg gfg gsg glg gpg gcr gfr gsr glr gpr gcw gfw gsw glw gpw skc skf sku skl skz".split(),
    "runes": [f"r{i:02}" for i in range(1, 34)],
    "keys": ["key"],
    "health_potions": [f"hp{i}" for i in range(1, 6)],
    "mana_potions": [f"mp{i}" for i in range(1, 6)],
    "rejuvenation_potions": ["rvs", "rvl"],

}
REIMAGINED = {
    "gems": "gmm gmt gms gme gmr gmd gmk gmo".split(),
    "gem_stacks": "1am 1tp 1sa 1em 1rb 1di 1sk 1so".split(),
    "rune_stacks": [f"s{i:02}" for i in range(1, 34)],
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tables', type=Path, help='Optional Excel tables directory used only for display names')
    args = parser.parse_args()
    names = {}
    for name in ("misc.txt", "weapons.txt"):
        p = args.tables / name if args.tables else None
        if p is not None and p.exists():
            with p.open(encoding="utf-8-sig") as f:
                names.update({r["code"]: r.get("name", r["code"]) for r in csv.DictReader(f, delimiter="\t") if r.get("code")})
    catalog = []
    for scope, groups in (("vanilla", VANILLA), ("reimagined", REIMAGINED)):
        for group, codes in groups.items():
            for code in codes:
                catalog.append({"code": code, "name": names.get(code, code), "scope": scope, "group": group})
    assert len({r["code"] for r in catalog}) == len(catalog)
    (ROOT / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n")
    header = "// Generated by prepare.py; vanilla codes and optional Reimagined codes.\n#pragma once\n#include <array>\n#include <string_view>\nnamespace RuffnecKk::AutoPickup {\n"
    for label, groups in (("Vanilla", VANILLA), ("Reimagined", REIMAGINED)):
        header += f"inline constexpr std::array<std::string_view, {len(groups)}> {label}Groups{{" + ", ".join(json.dumps(x) for x in groups) + "};\n"
    header += "struct CatalogEntry { std::string_view code; unsigned group; bool reimagined; };\n"
    header += f"inline constexpr std::array<CatalogEntry, {len(catalog)}> Catalog{{{{\n"
    for row in catalog:
        groups = REIMAGINED if row["scope"] == "reimagined" else VANILLA
        header += '    {"%s", %d, %s},\n' % (row["code"], list(groups).index(row["group"]), "true" if row["scope"] == "reimagined" else "false")
    header += "}};\n}\n"
    (ROOT / "src/catalog.hpp").write_text(header)
    print(f"Generated {len(catalog)} item codes; {len(VANILLA)} vanilla and {len(REIMAGINED)} Reimagined groups.")


if __name__ == "__main__":
    main()
